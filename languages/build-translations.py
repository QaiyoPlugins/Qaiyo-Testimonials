def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def write_po(path, locale, lang_name, translations, is_pot=False):
    today = datetime.now().strftime('%Y-%m-%d %H:%M+0000')
    header_msgstr = (
        f'Project-Id-Version: {DOMAIN} 1.0.0\\n'
        f'POT-Creation-Date: {today}\\n'
        f'PO-Revision-Date: {today}\\n'
        f'Last-Translator: Qaiyo by PixelDesigns <info@qaiyo-plugins.com>\\n'
        f'Language-Team: {lang_name}\\n'
        f'Language: {locale}\\n'
        f'MIME-Version: 1.0\\n'
        f'Content-Type: text/plain; charset=UTF-8\\n'
        f'Content-Transfer-Encoding: 8bit\\n'
        f'X-Generator: build-translations.py\\n'
    )
    lines = []
    lines.append('# Qaiyo Testimonials translations')
    lines.append('# Copyright (C) Qaiyo by PixelDesigns')
    lines.append('msgid ""')
    lines.append('msgstr ""')
    for chunk in header_msgstr.split('\\n')[:-1]:
        lines.append(f'"{chunk}\\n"')
    lines.append('')
    for s in STRINGS:
        lines.append(f'msgid "{po_escape(s)}"')
        target = '' if is_pot else translations.get(s, '')
        lines.append(f'msgstr "{po_escape(target)}"')
        lines.append('')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


def write_mo(path, translations):
    items = [('', 'Content-Type: text/plain; charset=UTF-8\n')]
    for s in STRINGS:
        if s in translations and translations[s]:
            items.append((s, translations[s]))
    items.sort(key=lambda x: x[0].encode('utf-8'))

    keys = b'\x00'.join(k.encode('utf-8') for k, _ in items) + b'\x00'
    vals = b'\x00'.join(v.encode('utf-8') for _, v in items) + b'\x00'

    n = len(items)
    header_size = 7 * 4
    offset_table_size = n * 8 * 2
    offsets_o = header_size
    offsets_t = offsets_o + n * 8
    keys_offset = offsets_t + n * 8

    key_offsets = []
    pos = keys_offset
    for k, _ in items:
        kb = k.encode('utf-8')
        key_offsets.append((len(kb), pos))
        pos += len(kb) + 1

    vals_offset = pos
    val_offsets = []
    pos = vals_offset
    for _, v in items:
        vb = v.encode('utf-8')
        val_offsets.append((len(vb), pos))
        pos += len(vb) + 1

    out = struct.pack('Iiiiiii', 0x950412de, 0, n, offsets_o, offsets_t, 0, 0)
    for l, o in key_offsets:
        out += struct.pack('ii', l, o)
    for l, o in val_offsets:
        out += struct.pack('ii', l, o)
    out += keys
    out += vals

    with open(path, 'wb') as f:
        f.write(out)


